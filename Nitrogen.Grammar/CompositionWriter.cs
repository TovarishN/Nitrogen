using System.Text;

namespace Nitrogen.Grammar;

/// <summary>Emits syntax composition only; callers register their semantic modules explicitly.</summary>
public static class CompositionWriter
{
    public static GrammarCompileResult Write(LanguageComposition composition)
    {
        var inputs = composition.Grammars.Distinct().ToArray();
        var diagnostics = new List<CompiledDiagnostic>();
        string path = inputs.FirstOrDefault()?.Path ?? "";
        string factory = composition.Name + "Composition";
        if (composition.Name.Length == 0 || !ValidIdentifier(factory) || composition.Namespace.Split('.').Any(s => !ValidIdentifier(s)))
            return Error("language name and namespace must be valid C# identifiers");
        var modules = new List<ModuleDecl>();
        var namespaces = new Dictionary<string, string>(StringComparer.Ordinal);
        var origins = new Dictionary<string, GrammarInput>(StringComparer.Ordinal);
        foreach (var input in inputs)
        {
            var parsed = GrammarParser.Parse(DocumentSignatures.Read(input.Text).MaskedText);
            diagnostics.AddRange(parsed.Diagnostics.Select(d => new CompiledDiagnostic(input.Path, d)));
            foreach (var module in parsed.File?.Modules ?? default)
            {
                modules.Add(module);
                namespaces[module.Name] = input.Namespace;
                origins[module.Name] = input;
            }
        }
        foreach (var diagnostic in GrammarValidator.Validate(modules))
            diagnostics.Add(new(diagnostic.Module is not null && origins.TryGetValue(diagnostic.Module, out var origin) ? origin.Path : path, diagnostic));
        if (diagnostics.Any(d => d.Diagnostic.Severity == GrammarSeverity.Error))
            return new(diagnostics.ToArray(), default);
        var model = new EmitModel(new GrammarAnalysis(modules), namespaces, origins);
        var selected = model.Modules.OrderBy(m => m.Module.Name, StringComparer.Ordinal).ToArray();
        int dot = composition.Start.LastIndexOf('.');
        var startModule = dot > 0 ? selected.FirstOrDefault(m => m.Module.Name == composition.Start.Substring(0, dot)) : null;
        string startName = dot > 0 ? composition.Start.Substring(dot + 1) : "";
        if (startModule is null || !model.Analysis.PrimaryRules(startModule.Module).OfType<SyntaxRule>().Any(r => r.Name == startName))
            return Error($"composition '{composition.Name}' requires a syntax start rule; unknown or unsupported start '{composition.Start}'");
        if (selected.Any(m => m.Namespace == composition.Namespace &&
            (m.ClassName == factory || m.KindsName == factory || m.VisitorName == factory || m.Kinds.Any(k => k.ViewName == factory))))
            return Error($"composition factory '{factory}' collides with a generated type");
        string Ref(ModuleInfo module) => "global::" + module.Namespace + "." + CSharpText.Identifier(module.ClassName);
        var code = new StringBuilder("// <auto-generated/>\n#nullable enable\n\n")
            .Append("namespace ").Append(composition.Namespace).Append(";\n\npublic static class ").Append(factory)
            .Append("\n{\n    public static global::Nitrogen.LanguageBuilder CreateBuilder() =>\n        new global::Nitrogen.LanguageBuilder()");
        foreach (var module in selected) code.Append("\n            .Add(").Append(Ref(module)).Append(".Instance)");
        code.Append(";\n\n    public static global::Nitrogen.Rule Start => ").Append(Ref(startModule)).Append('.')
            .Append(CSharpText.Identifier(startName)).Append(";\n}\n");
        return new(diagnostics.ToArray(), new[] { new GeneratedSource(composition.FactoryHintName, code.ToString()) });

        GrammarCompileResult Error(string message) => new(new[] { new CompiledDiagnostic(path,
            new GrammarDiagnostic("NGR0406", GrammarSeverity.Error, message, default)) }, default);
    }

    internal static bool ValidIdentifier(string value) => value.Length > 0 &&
        (value[0] == '_' || char.IsLetter(value[0])) && value.Skip(1).All(c => c == '_' || char.IsLetterOrDigit(c)) &&
        CSharpText.Identifier(value) == value;
}
